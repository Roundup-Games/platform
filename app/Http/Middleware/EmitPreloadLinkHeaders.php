<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Vite;
use Symfony\Component\HttpFoundation\Response;

/**
 * Mirror preload hints into Link response headers so Cloudflare can replay
 * them as 103 Early Hints (Speed → Optimization → Early Hints).
 *
 * A <link rel="preload"> inside the HTML body is only discovered after TTFB,
 * once the browser has parsed the document head. Cloudflare, in contrast,
 * learns Link headers from prior responses and replays them as a 103 BEFORE
 * the origin even answers — so critical subresources (LCP image, stylesheet,
 * fonts) download during the origin's think-time instead of after it.
 *
 * Emitted only for the same population CachePublicPages serves: anonymous
 * GET HTML. Authenticated responses keep their private cache-control and are
 * never used to seed edge hints.
 *
 * Hints are capped: the two self-hosted text fonts, the app stylesheet, and
 * up to two LCP image preloads discovered in the response body (hero images
 * pushed via @push('preload') by the game/campaign/game-system headers).
 * Everything hinted here is already preloaded in the HTML — Chrome/Edge
 * dedupe reliably; the worst case on older Safari builds is a wasted fetch
 * of a ~50KB webp.
 */
class EmitPreloadLinkHeaders
{
    /** Maximum as=image preloads mirrored from the body into the header */
    protected const MAX_IMAGE_HINTS = 2;

    /** Self-hosted woff2 fonts preloaded in the public layout head */
    protected const PRELOADED_FONTS = [
        '/fonts/inter-latin-var.woff2',
        '/fonts/noto-serif-latin-var.woff2',
    ];

    public function handle(Request $request, Closure $next): Response
    {
        $response = $next($request);

        if (
            $request->isMethod('GET')
            && ! $request->routeIs('api.*')
            && ! $request->is('api/*')
            && ! auth()->check()
            && $response->isSuccessful()
            && str_contains((string) $response->headers->get('Content-Type'), 'text/html')
        ) {
            $links = [
                ...array_map(
                    fn (string $font) => sprintf('<%s>; rel=preload; as=font; type="font/woff2"; crossorigin', $font),
                    self::PRELOADED_FONTS,
                ),
            ];

            $stylesheet = $this->appStylesheetUrl();
            if ($stylesheet !== null) {
                $links[] = sprintf('<%s>; rel=preload; as=style', $stylesheet);
            }

            foreach ($this->heroImageUrls($response->getContent() ?? '') as $imageUrl) {
                $links[] = sprintf('<%s>; rel=preload; as=image; fetchpriority=high', $imageUrl);
            }

            $response->headers->set('Link', implode(', ', $links));
        }

        return $response;
    }

    /**
     * Hashed app stylesheet URL from the Vite manifest. Null when the build
     * manifest is unavailable (dev server without hot file etc.) — the hint
     * is an optimization, never a hard requirement.
     */
    protected function appStylesheetUrl(): ?string
    {
        try {
            return Vite::asset('resources/css/app.css');
        } catch (\Throwable) {
            return null;
        }
    }

    /**
     * Extract hero-image preload URLs the page templates pushed into <head>.
     *
     * Matches the exact shape emitted by the hero partials' @push('preload')
     * blocks — machine-generated by our own Blade, so a targeted regex is
     * cheaper and more predictable than DOM-parsing a full page.
     *
     * @return list<non-empty-string>
     */
    protected function heroImageUrls(string $content): array
    {
        if ($content === '') {
            return [];
        }

        $matched = preg_match_all(
            '/<link rel="preload" as="image" href="([^"]+)" fetchpriority="high">/',
            $content,
            $matches,
        );

        if ($matched === false || $matched === 0) {
            return [];
        }

        /** @var list<non-empty-string> $captured */
        $captured = $matches[1];

        return array_slice($captured, 0, self::MAX_IMAGE_HINTS);
    }
}
